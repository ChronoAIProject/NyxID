    second.unwrap();
    old_startup.unwrap();
    super::super::platform_public_agent_service::ensure_indexes(&db)
        .await
        .unwrap();
    let indexes: Vec<_> = legacy
        .list_indexes()
        .await
        .unwrap()
        .try_collect()
        .await
        .unwrap();
    let old_unique = indexes
        .iter()
        .find(|index| {
            index
                .options
                .as_ref()
                .and_then(|options| options.name.as_deref())
                == Some("candidate_digest_1")
        })
        .unwrap();
