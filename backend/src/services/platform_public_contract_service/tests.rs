async fn stored_deployment(
    db: &Database,
) -> (DownstreamService, DownstreamService, DeploymentEvidence) {
    let outer = outer();
    let model = model();
    db.collection::<DownstreamService>(SERVICES)
        .insert_many([&outer, &model])
        .await
        .unwrap();
    db.collection::<Document>(crate::models::user::COLLECTION_NAME)
        .insert_one(doc! {"_id":binding().sponsor_owner_user_id,"user_type":"org","is_active":true})
        .await
        .unwrap();
    let e = evidence(&outer, &model, &[]);
    validate_manifest(&e.manifest)
        .expect("stored catalog digests must satisfy the public wire contract");
    fence(db, &e)
        .await
        .expect("stored deployment must authorize before any negative or race assertion");
    (outer, model, e)
}
async fn fence(db: &Database, e: &DeploymentEvidence) -> AppResult<()> {
    let mut session = db.client().start_session().await?;
    session
        .start_transaction()
        .and_run2(async |s| tx::transaction_result(fence_deployment(db, s, e).await))
        .await
        .map_err(tx::map_transaction_error)
}

