export const placeCatalogs = (merged, sources, existing = {}) => tools.placeCatalogs(merged, sources, existing, scan);

/**
 * Barrel import names: `${camelCase}Catalog`, built from the area's ASCII
 * letters and digits. The `Catalog` suffix keeps reserved words (`delete`,
 * `default`) valid, an `area` prefix covers names that are empty or start with
 * a digit, and a numeric suffix resolves collisions (`foo-bar` vs `fooBar`) in
 * sorted area order.
 */
export function barrelIdentifiers(areas) {
  const used = new Set(["catalog"]);
  return new Map([...areas].sort(core.codeUnitCompare).map((area) => {
    const words = area.split(/[^A-Za-z0-9]+/).filter(Boolean);
    let camel = words.map((word, index) => index ? word[0].toUpperCase() + word.slice(1) : word[0].toLowerCase() + word.slice(1)).join("");
    if (!/^[A-Za-z]/.test(camel)) camel = `area${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
    let name = `${camel}Catalog`;
    for (let suffix = 2; used.has(name); suffix++) name = `${camel}Catalog${suffix}`;
    used.add(name);
    return [area, name];
  }));
}

/** The barrel re-exports every area catalog of one language, imported explicitly in sorted order. */
export function barrelText(areas, language) {
  const names = barrelIdentifiers(areas);
  return [
    "// Generated by `pnpm sync:i18n` from the area directories; do not edit by hand.",
    ...[...names].map(([area, name]) => `import ${name} from ${JSON.stringify(`./${area}/${language}.json`)};`),
    "",
    "const catalog = {",
    ...[...names.values()].map((name) => `  ...${name},`),
    "};",
    "",
    "export default catalog;",
    "",
  ].join("\n");
}
export const barrelFile = (language, dir = locales) => path.join(dir, `${language}.ts`);

/** Write the non-empty area catalogs (pruning emptied areas) and both barrels. */
export function writeCatalogs(portions, dir = locales) {
  tools.writePortions(dir, Object.fromEntries(Object.entries(portions)
    .filter(([, catalogs]) => LANGUAGES.some((language) => Object.keys(catalogs[language]).length))));
  const areas = core.discoverPortions(dir);
  for (const language of LANGUAGES) {
    const file = barrelFile(language, dir);
    const text = barrelText(areas, language);
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
  }
}

const placeholders = (text) => (text.match(/\{\{\w+\}\}/g) ?? []).sort(core.codeUnitCompare).join("\0");

/**
 * Every invariant CI enforces on the mobile catalogs: no legacy monolith, only
 * area directories and barrels, canonical sorted JSON, per-area language parity,
 * placeholders matching the English phrase, no differing cross-area duplicates,
 * and barrels importing exactly the existing areas.
 */
export function auditCatalogs(dir = locales) {
  const issues = legacyFiles(dir).map((file) => `legacy monolith ${path.basename(file)} is present; ${ADOPT_HINT}`);
  const areas = core.discoverPortions(dir);
  const barrels = new Set(LANGUAGES.map((language) => `${language}.ts`));
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory() || barrels.has(entry.name) || legacyFiles(dir).some((file) => path.basename(file) === entry.name)) continue;
    issues.push(`unexpected file ${entry.name}; catalogs live in <area>/{${LANGUAGES.join(",")}}.json`);
  }
  const portions = {};
  for (const area of areas) {
    const expected = new Set(LANGUAGES.map((language) => `${language}.json`));
    for (const name of fs.readdirSync(path.join(dir, area))) {
      if (!expected.has(name)) issues.push(`${area}/${name}: unexpected file; areas hold only ${[...expected].join(" and ")}`);
    }
    portions[area] = emptyLanguages();
    for (const language of LANGUAGES) {
      const file = core.portionFile(dir, area, language);
      if (!fs.existsSync(file)) { issues.push(`${area}: missing ${language}.json`); continue; }
      try {
        const text = fs.readFileSync(file, "utf8");
        portions[area][language] = JSON.parse(text);
        if (text !== core.canonicalText(portions[area][language])) issues.push(`${area}/${language}.json: non-canonical catalog; run pnpm sync:i18n`);
      } catch (error) {
        issues.push(`${area}/${language}.json: invalid catalog (${error.message})`);
      }
    }
  }
  const analysis = analyzePortions(portions);
  issues.push(...analysis.issues);
  for (const [area, catalogs] of Object.entries(portions)) {
    for (const language of LANGUAGES) {
      for (const [phrase, translation] of Object.entries(catalogs[language])) {
        if (typeof translation !== "string" || !translation.trim()) issues.push(`${area}/${language}.json: empty translation: ${phrase}`);
        else if (placeholders(translation) !== placeholders(phrase)) issues.push(`${area}/${language}.json: placeholders differ from the phrase: ${phrase}`);
      }
    }
  }
  for (const language of LANGUAGES) {
    const file = barrelFile(language, dir);
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== barrelText(areas, language)) {
      issues.push(`${language}.ts: barrel must import exactly the area catalogs (${areas.join(", ")}); run pnpm sync:i18n`);
    }
  }
  return issues;
}

/** Pre-split monoliths and the barrel each import must use instead (mobile has no import aliases). */
export const LEGACY_CATALOG_IMPORTS = {
  "src/i18n/locales/zh-CN.json": "src/i18n/locales/zh-CN",
  "src/i18n/locales/zh-TW.json": "src/i18n/locales/zh-TW",
};
export const moduleSpecifiers = core.moduleSpecifierLister(ts);

/** Rewrite legacy catalog imports in mobile/src (tests included), printing each rewrite. */
export const rewriteLegacyCatalogImports = (dir = root) => core.rewriteLegacyImportsInTree({
  root: dir, dir: "src", specifiers: moduleSpecifiers, legacy: LEGACY_CATALOG_IMPORTS, aliases: [], typecheck: "pnpm typecheck",
});

/** Remaining imports of a legacy catalog path in any mobile/src source, tests included. */
export function legacyImportIssues(dir = root) {
  const { rewrites } = core.rewriteLegacyImports(core.legacyImportCandidates(dir, "src", LEGACY_CATALOG_IMPORTS), moduleSpecifiers, LEGACY_CATALOG_IMPORTS, []);
  return rewrites.map(({ file, line, from, to }) =>
    `${file}:${line}: legacy catalog import ${from}; use ${to} (pnpm adopt:i18n rewrites it; outside a merge or rebase run pnpm adopt:i18n --imports-only)`);
}
